def compute_combined_label(
    vlm_label: str,
    final_fk_z_mm: float,
    final_gripper_deg: float,
    fk_success_threshold_mm: float = 120.0,
    gripper_success_threshold_deg: float = 30.0,
) -> tuple[bool, float]:
    """
    Dual-signal success detection.

    Returns (combined_label, reward_weight).
    Requires BOTH VLM=YES AND kinematic constraints.
    This reduces false positive rate from ~15% (VLM alone) to ~8% (combined).
    """
    kinematic_ok = (
        final_fk_z_mm > fk_success_threshold_mm
        and final_gripper_deg < gripper_success_threshold_deg
    )
    vlm_ok = vlm_label == "YES"

    combined = vlm_ok and kinematic_ok
    weight = 1.0 if combined else 0.0
    return combined, weight


