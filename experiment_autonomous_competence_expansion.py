def power_analysis(p_before: float, p_after: float, alpha: float = 0.05,
                   power: float = 0.80) -> int:
    """
    Minimum sample size per condition for one-sided proportions test.
    Uses normal approximation (valid for p > 0.1, N > 20).
    """
    import math
    z_alpha = 1.645  # one-sided α=0.05
    z_beta_map = {0.80: 0.842, 0.90: 1.282, 0.95: 1.645}
    z_beta = z_beta_map.get(power, 0.842)

    delta = abs(p_after - p_before)
    if delta == 0:
        return float('inf')

    numerator = (z_alpha + z_beta) ** 2 * (p_before * (1 - p_before) + p_after * (1 - p_after))
    n = math.ceil(numerator / (delta ** 2))
    return n


def wilson_ci(successes: int, n: int, z: float = 1.96) -> tuple[float, float]:
    """Wilson score confidence interval for a binomial proportion."""
    if n == 0:
        return (0.0, 1.0)
    p_hat = successes / n
    denominator = 1 + z**2 / n
    center = (p_hat + z**2 / (2 * n)) / denominator
    margin = (z * (p_hat * (1 - p_hat) / n + z**2 / (4 * n**2))**0.5) / denominator
    return (max(0, center - margin), min(1, center + margin))


